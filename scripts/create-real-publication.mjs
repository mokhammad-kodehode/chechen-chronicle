function makeKey() {
  return Math.random().toString(36).slice(2, 14);
}

function paragraphBlock(text) {
  return {
    _type: "block",
    _key: makeKey(),
    style: "normal",
    markDefs: [],
    children: [{ _type: "span", _key: makeKey(), text, marks: [] }],
  };
}

async function main() {
  // Находим автора по имени (без учёта регистра, частичное совпадение)
  const author = await client.fetch(
    `*[_type == "person" && name match "Амин*"][0]{_id, name}`
  );
  if (!author) {
    console.error(
      '✗ Автор «Амин ...» не найден в Sanity. Создайте Person в Studio и запустите снова.'
    );
    process.exit(1);
  }
  console.log(`→ Использую автора: ${author.name} (${author._id})`);

  const slug = "zakat-epokhi-ansi-v-chechenskom-mokhke";

  const existing = await client.fetch(
    `*[_type == "publication" && slug.current == $slug][0]{_id}`,
    { slug }
  );
  if (existing) {
    console.log(`• Публикация с этим slug уже есть: ${existing._id}`);
    return;
  }

  const doc = {
    _type: "publication",
    title: "Закат эпохи «анси» в чеченском Мохке",
    slug: { _type: "slug", current: slug },
    excerpt:
      "Хроника смены лидеров Чеченского Мохка после похода Тимура 1395 года — от казни Хоура до возвышения Берг-Биччи как первого «воккхала» в конце XV века.",
    author: { _type: "reference", _ref: author._id },
    publishedAt: new Date().toISOString(),
    category: "research",
    tags: ["XV век", "Тимур", "Мохк", "лидерство", "анси"],
    featured: true,
    body: PARAGRAPHS.map(paragraphBlock),
  };

  const created = await client.create(doc);
  console.log(`✓ Создана публикация: ${created.title}`);
  console.log(`  _id:  ${created._id}`);
  console.log(`  slug: ${slug}`);
  console.log(`  url:  http://localhost:3000/ru/publications/${slug}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
